// Shared config for the devnet scripts. Never prints or logs secret key material.
import * as fs from "fs";
import * as path from "path";
import { Connection, Keypair, PublicKey } from "@solana/web3.js";

export const ROOT = path.resolve(__dirname, "../..");
export const KEYS_DIR = path.join(ROOT, ".keys");
export const DEVNET_JSON = path.join(ROOT, "devnet.json");
export const ENV_GENERATED = path.join(KEYS_DIR, "env.generated");
export const DEVNET_GENESIS = "EtWTRABZaYq6iMfeYKouRu166VU2xqa1wcaWoxPkrZBG";
export const DEFAULT_RPC = "https://api.devnet.solana.com";
export const ROLES = ["payer", "oracle", "treasury", "mint-authority", "upgrade-authority", "program-keypair"] as const;
export type Role = (typeof ROLES)[number];
export const LAMPORTS = 1_000_000_000;
export const USDC = 1_000_000n;

export const log = (...a: any[]) => console.log(...a);
export const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
export const sol = (lamports: number | bigint) => (Number(lamports) / LAMPORTS).toFixed(6);
export const explorerTx = (sig: string) => `https://explorer.solana.com/tx/${sig}?cluster=devnet`;
export const explorerAddr = (a: string | PublicKey) => `https://explorer.solana.com/address/${a.toString()}?cluster=devnet`;

export function rpcUrl(): string {
  return process.env.SOLANA_RPC_URL || DEFAULT_RPC;
}

export function makeConnection(): Connection {
  // our own retry/backoff below, so the web3.js one is off
  return new Connection(rpcUrl(), { commitment: "confirmed", disableRetryOnRateLimit: true });
}

/** Abort unless the RPC really is devnet (genesis hash, so it also works for custom provider URLs). */
export async function guardDevnet(conn: Connection): Promise<void> {
  let hash: string;
  try {
    hash = await withRetry("getGenesisHash", () => conn.getGenesisHash());
  } catch (e: any) {
    throw new Error(`Cannot reach the RPC ${safeUrl()}: ${e.message}`);
  }
  if (hash !== DEVNET_GENESIS) {
    throw new Error(`ABORT: ${safeUrl()} is not devnet (genesis ${hash}). These scripts only run on devnet. Check SOLANA_RPC_URL.`);
  }
}
function safeUrl(): string {
  try { const u = new URL(rpcUrl()); return `${u.protocol}//${u.host}`; } catch { return "<invalid SOLANA_RPC_URL>"; }
}

export async function withRetry<T>(label: string, fn: () => Promise<T>, delays = [2000, 4000, 8000, 16000]): Promise<T> {
  for (let i = 0; ; i++) {
    try {
      return await fn();
    } catch (e: any) {
      const msg = String(e?.message ?? e);
      const transient = /429|too many|rate.?limit|fetch failed|ECONNRESET|ETIMEDOUT|ENOTFOUND|timed? ?out|503|502/i.test(msg);
      if (!transient) throw e;
      if (i >= delays.length) throw new Error(`${label}: the RPC keeps rate limiting or failing (${msg.slice(0, 100)}). Slow down and retry later.`);
      log(`  (${label}: RPC busy, waiting ${delays[i] / 1000}s)`);
      await sleep(delays[i]);
    }
  }
}

// ---- keys ----
export const keyPath = (role: Role) => path.join(KEYS_DIR, `${role}.json`);

export function loadKeypair(role: Role): Keypair {
  const p = keyPath(role);
  if (!fs.existsSync(p)) throw new Error(`Missing ${path.relative(ROOT, p)}. Run: npm run keys`);
  const mode = fs.statSync(p).mode & 0o777;
  if (mode & 0o077) throw new Error(`${path.relative(ROOT, p)} has mode ${mode.toString(8)}; run chmod 600 on it`);
  return Keypair.fromSecretKey(Uint8Array.from(JSON.parse(fs.readFileSync(p, "utf8"))));
}
export const secretB64 = (k: Keypair) => Buffer.from(k.secretKey).toString("base64");

// ---- devnet.json (public keys only) ----
export type DevnetJson = {
  cluster: "devnet";
  rpcDefault: string;
  programId?: string;
  deploySignature?: string;
  testUsdcMint?: string;
  decimals: 6;
  keys: { payer: string; oracle: string; treasury: string; mintAuthority: string; upgradeAuthority: string; program: string };
};
export function readDevnet(): DevnetJson {
  if (!fs.existsSync(DEVNET_JSON)) throw new Error("devnet.json missing. Run: npm run keys");
  return JSON.parse(fs.readFileSync(DEVNET_JSON, "utf8"));
}
export function writeDevnet(d: DevnetJson) {
  fs.writeFileSync(DEVNET_JSON, JSON.stringify(d, null, 2) + "\n");
}

/** Regenerate the gitignored env file (mode 600). Contents are never printed. */
export function writeEnvGenerated() {
  const d = readDevnet();
  const lines = [
    "# generated by contracts/scripts, gitignored, contains SECRETS. Copy into the backend env file / host settings.",
    `SOLANA_RPC_URL=${DEFAULT_RPC}`,
    `PROGRAM_ID=${d.programId ?? ""}`,
    `TEST_USDC_MINT=${d.testUsdcMint ?? ""}`,
    `PAYER_SECRET_KEY=${secretB64(loadKeypair("payer"))}`,
    `ORACLE_SECRET_KEY=${secretB64(loadKeypair("oracle"))}`,
    `TREASURY_PUBKEY=${d.keys.treasury}`,
    `MINT_AUTHORITY_SECRET_KEY=${secretB64(loadKeypair("mint-authority"))}`,
    "",
  ];
  fs.writeFileSync(ENV_GENERATED, lines.join("\n"), { mode: 0o600 });
  fs.chmodSync(ENV_GENERATED, 0o600);
}

export function run(main: () => Promise<void>) {
  main().catch((e) => {
    console.error("\nERROR:", e?.message ?? e);
    process.exit(1);
  });
}
